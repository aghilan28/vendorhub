function asCategory(seed: CategorySeed): { name: string; attributeKeys?: string[]; subcategories?: SubcategorySeed[] } {
  return typeof seed === "string" ? { name: seed } : seed;
}

function asSubcategory(seed: SubcategorySeed): { name: string; families?: FamilySeed[] } {
  return typeof seed === "string" ? { name: seed } : seed;
}

function asType(seed: TypeSeed): { name: string; variantGroups?: string[] } {
  return typeof seed === "string" ? { name: seed } : seed;
}

/**
 * Expands {@link CANONICAL_DEPARTMENTS} into deterministic engine inputs. IDs are the hierarchical
 * slug (e.g. `dairy-milk-liquid-milk`), guaranteeing global uniqueness and stable parent links.
 */
export function buildCanonicalTaxonomyInputs(): TaxonomyNodeInput[] {
  const inputs: TaxonomyNodeInput[] = [];

  CANONICAL_DEPARTMENTS.forEach((department, departmentIndex) => {
    const departmentSlug = slugify(department.name);
    inputs.push({
      id: departmentSlug,
      level: "DEPARTMENT",
      name: department.name,
      parentId: null,
      regions: department.regions,
      attributeKeys: department.attributeKeys,
      sortOrder: departmentIndex,
    });

    asCategoryList(department.categories).forEach((category, categoryIndex) => {
      const categorySlug = `${departmentSlug}-${slugify(category.name)}`;
      inputs.push({
        id: categorySlug,
        level: "CATEGORY",
        name: category.name,
        parentId: departmentSlug,
        attributeKeys: category.attributeKeys,
        sortOrder: categoryIndex,
      });

      (category.subcategories ?? []).forEach((subSeed, subIndex) => {
        const subcategory = asSubcategory(subSeed);
        const subcategorySlug = `${categorySlug}-${slugify(subcategory.name)}`;
        inputs.push({
          id: subcategorySlug,
          level: "SUBCATEGORY",
          name: subcategory.name,
          parentId: categorySlug,
          sortOrder: subIndex,
        });

        (subcategory.families ?? []).forEach((family, familyIndex) => {
          const familySlug = `${subcategorySlug}-${slugify(family.name)}`;
          inputs.push({
            id: familySlug,
            level: "PRODUCT_FAMILY",
            name: family.name,
            parentId: subcategorySlug,
            attributeKeys: family.attributeKeys,
            sortOrder: familyIndex,
          });

          (family.types ?? []).forEach((typeSeed, typeIndex) => {
            const type = asType(typeSeed);
            const typeSlug = `${familySlug}-${slugify(type.name)}`;
            inputs.push({
              id: typeSlug,
              level: "PRODUCT_TYPE",
              name: type.name,
              parentId: familySlug,
              sortOrder: typeIndex,
            });

            (type.variantGroups ?? []).forEach((variantName, variantIndex) => {
              inputs.push({
                id: `${typeSlug}-${slugify(variantName)}`,
                level: "VARIANT_GROUP",
                name: variantName,
                parentId: typeSlug,
                sortOrder: variantIndex,
              });
            });
          });
        });
      });
    });
  });

  return inputs;
}

function asCategoryList(categories: CategorySeed[]) {
  return categories.map(asCategory);
}
