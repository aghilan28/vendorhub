type SubcategorySeed = string | { name: string; families?: FamilySeed[] };
type CategorySeed = string | { name: string; attributeKeys?: string[]; subcategories?: SubcategorySeed[] };

interface DepartmentSeed {
  name: string;
  regions?: CommerceRegion[];
  attributeKeys?: string[];
  categories: CategorySeed[];
}

