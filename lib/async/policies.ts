export function priorityValue(priority: AsyncJobPriority | undefined, policy: QueuePolicy) {
  if (typeof priority === "number") return Math.max(0, Math.min(100, priority));
  if (priority === "critical") return 95;
  if (priority === "high") return 80;
  if (priority === "low") return 20;
  return policy.priority;
}

export function retryDelayForAttempt(policy: QueuePolicy, attempt: number, pressure = 0) {
  const jitterWindow = Math.max(5, Math.floor(policy.baseRetryDelaySeconds / 2));
  const jitterSeed = createHash("sha256").update(`${policy.queueName}:${policy.category}:${attempt}`).digest("hex").slice(0, 8);
  const jitter = Number.parseInt(jitterSeed, 16) % jitterWindow;
  const exponential = policy.baseRetryDelaySeconds * 2 ** Math.max(0, attempt - 1);
  const pressureBackoff = Math.ceil(Math.max(0, pressure) * policy.saturationBackoffSeconds);
  return Math.min(policy.maxRetryDelaySeconds, exponential + jitter + pressureBackoff);
}

export function expandQueueNames(queueNames: string[]) {
  return [...new Set(queueNames.flatMap((queueName) => queueAliases[queueName] ?? [queueName]))];
}

