export function concurrencyLimitsForQueues(queueNames: string[], pressureByQueue: Record<string, number> = {}) {
  const expanded = expandQueueNames(queueNames);
  const limits = Object.values(queuePolicies).reduce<Record<string, number>>((current, policy) => {
    const pressure = pressureByQueue[policy.queueName] ?? 0;
    const elastic = pressure > 0.75 ? policy.maxElasticConcurrency : policy.concurrency;
    current[policy.queueName] = Math.max(current[policy.queueName] ?? 0, Math.max(policy.minReservedConcurrency, elastic));
    return current;
  }, {});

  return Object.fromEntries(expanded.map((queueName) => [queueName, limits[queueName] ?? 1]));
}

export function lockSecondsForQueues(queueNames: string[]) {
  const expanded = expandQueueNames(queueNames);
  return Math.max(
    30,
    ...Object.values(queuePolicies)
      .filter((policy) => expanded.includes(policy.queueName))
      .map((policy) => policy.timeoutSeconds + 30),
  );
}
